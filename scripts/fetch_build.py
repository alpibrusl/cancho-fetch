#!/usr/bin/env python3
"""Build `fetch` for an allow-list: write generated/fetch/fetch.cho, derive the manifest, build, gate.

    python3 scripts/fetch_build.py --host http://127.0.0.1:8080 [--host ...] [--allow-private] [--out build/fetch]

A capability's bound is a literal, so every host has its own function and its own `Out("host:port")` (docs/design.md
section 5); the hosts are therefore the build's input, and the authority row is derived from them, not declared. An
entry is `scheme://host[:port]`; only `http` is built so far (HTTPS is a later step). `--allow-private` lets the
build talk to a loopback, private or link-local peer (for tests and for internal services); without it the peer check
refuses them (`fetch.peer-not-public`).
"""

import argparse
import os
import pathlib
import re
import sys
import procs as subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENTRY = re.compile(r"^(https?)://([A-Za-z0-9.*-]+)(?::([0-9]{1,5}))?$")


def bound(entry):
    m = ENTRY.match(entry)
    if not m:
        sys.exit("fetch_build: %r is not http(s)://host[:port]" % entry)
    return "%s:%s" % (m.group(2), m.group(3) or ("443" if m.group(1) == "https" else "80"))


def secure(entry):
    return entry.startswith("https://")


def literal(text):
    """A cancho string literal (the six escapes manifest.literal knows)."""
    import manifest
    return manifest.literal(text)


TOKEN = re.compile(r"^[A-Za-z0-9!#$%&'*+.^_`|~-]+$")


def parse_credentials(entries, specs):
    """`HOST=PATH[,Header]` -> {entry index: (path, header)}. Only an https:// entry may hold a credential (a bearer token is
    not sent in clear), a host is named once, the path is absolute and plain, the header a token (default Authorization)."""
    bounds = [bound(e) for e in entries]
    found = {}
    for spec in specs:
        host, eq, rest = spec.partition("=")
        path, _, header = rest.partition(",")
        if not eq or not host or not path:
            sys.exit("fetch_build: --credential is HOST=PATH[,Header], not %r" % spec)
        matches = [i for i, b in enumerate(bounds) if b == host or b.rsplit(":", 1)[0] == host and not any(x == host for x in bounds)]
        if len(matches) != 1:
            sys.exit("fetch_build: --credential %r names no single --host entry (the entries are %s)" % (spec, ", ".join(bounds)))
        i = matches[0]
        if not secure(entries[i]):
            sys.exit("fetch_build: --credential %r is for a plain http:// host; a token is only sent over https" % spec)
        if i in found:
            sys.exit("fetch_build: --credential names %s twice" % bounds[i])
        if not path.startswith("/") or not re.match(r"^[A-Za-z0-9._/-]+$", path) or ".." in path.split("/"):
            sys.exit("fetch_build: the credential path %r must be absolute, with letters, digits and . _ / - only, and no .." % path)
        if header and not TOKEN.match(header):
            sys.exit("fetch_build: %r is not a header name" % header)
        if header.lower() in ("host", "content-length", "transfer-encoding", "connection", "cookie", "proxy-authorization"):
            sys.exit("fetch_build: a credential cannot be sent as %s" % header)
        found[i] = (path, header or "Authorization")
    return found


def source(entries, allow_private, roots_pem, credentials=None):
    credentials = credentials or {}
    bounds = [bound(e) for e in entries]
    n = len(bounds)
    https = any(secure(e) for e in entries)
    if https and not roots_pem:
        sys.exit("fetch_build: an https:// host needs --roots FILE (the PEM bundle of the authorities it is trusted through)")
    rows = ", ".join(['net_out("%s")' % b for b in bounds] + ['fs_read("%s")' % credentials[i][0] for i in sorted(credentials)])
    out = []
    w = out.append
    w("edition 11;\n")
    w("// GENERATED by scripts/fetch_build.py for the hosts below -- do not edit. The hosts are the `Out` capability's bound, a")
    w("// literal, so each one has its own function; everything else is tools/fetch/fetchcore.cho.\n")
    w("import std.buffer;\nimport std.bytes;\nimport std.io;\nimport toolbox.cli;\nimport toolbox.describe;\nimport fetchcore;\n")
    w("fn hosts() -> [] &static [byte] {\n    return \"%s\";\n}\n" % ";".join(entries))
    w("fn roots() -> [] &static [byte] {\n    return %s;\n}\n" % literal(roots_pem if https else ""))
    w("fn credentials() -> [] &static [byte] {\n    return %s;\n}\n" % literal(";".join("%s=%s,%s" % (bounds[i], credentials[i][0], credentials[i][1]) for i in sorted(credentials))))
    w("fn private_ok() -> [] bool {\n    return %s;\n}\n" % ("true" if allow_private else "false"))
    for i, b in enumerate(bounds):
        cred = credentials.get(i)
        fs_param = ', cred: &f Fs("%s")' % cred[0] if cred else ""
        fs_row = ', fs_read("%s")' % cred[0] if cred else ""
        fs_gen = ", &f" if cred else ""
        w('fn via_%d[&h, &k, &o, &p, &y%s](heap: &!h Heap, clock: &k Clock, out: &o Out("%s"), plan: &p fetchcore.Plan, entropy: &y [byte]%s) -> [heap, clock, poll, net_out("%s")%s] fetchcore.Answer {' % (i, fs_gen, b, fs_param, b, fs_row))
        call = "fetchcore.exchange(heap, clock, conn, plan, fetchcore.authority(hosts(), %d), hosts(), private_ok(), fetchcore.entry_secure(hosts(), %d), fetchcore.dial_host(hosts(), %d), roots(), entropy, %s, %s)"
        if cred:
            w("    region keyring {")
            w("        let token = alloc_slice[keyring](4096, byte_of(0));")
            w("        var got = 0 - 1;")
            w('        got = fs_read(cred, "%s", token);' % cred[0])
            w("        let used = fetchcore.secret_len(token, got);")
            w('        if !fetchcore.secret_ok(token[0..used]) {\n            bytes.zero(token);\n            return fetchcore.credential_unavailable(heap, "%s");\n        }' % cred[0])
            w("        match tcp_connect(out, fetchcore.dial_host(hosts(), %d), fetchcore.dial_port(hosts(), %d)) {" % (i, i))
            w("            Dialed::Ok(conn) => {\n                let result = %s;\n                bytes.zero(token);\n                return result;\n            }" % (call % (i, i, i, "token[0..used]", literal(cred[1]))))
            w("            Dialed::Failed(errno) => {\n                bytes.zero(token);\n                return fetchcore.dial_failed(heap, errno);\n            }\n        }\n    }\n}\n")
        else:
            w("    match tcp_connect(out, fetchcore.dial_host(hosts(), %d), fetchcore.dial_port(hosts(), %d)) {" % (i, i))
            w("        Dialed::Ok(conn) => {\n            return %s;\n        }" % (call % (i, i, i, '""', '""')))
            w("        Dialed::Failed(errno) => {\n            return fetchcore.dial_failed(heap, errno);\n        }\n    }\n}\n")
    params = ", ".join(["o%d: &q%d Out(\"%s\")" % (i, i, b) for i, b in enumerate(bounds)] + ["f%d: &d%d Fs(\"%s\")" % (i, i, credentials[i][0]) for i in sorted(credentials)])
    gens = ", ".join(["&q%d" % i for i in range(n)] + ["&d%d" % i for i in sorted(credentials)])
    w("fn run[&h, &g, &i, &k, &z, %s](heap: &!h Heap, args: &g Args, io: &!i Io, clock: &k Clock, entropy: &z [byte], %s) -> [heap, args, io_read, io_write, err_write, clock, poll, %s] int {" % (gens, params, rows))
    w("    let which = cli.subcommand(args);\n    if which != 0 {\n        return describe.answer(heap, io, which, fetchcore.tool(), fetchcore.built());\n    }")
    w("    var plan = fetchcore.plan(heap, args, hosts());")
    w("    plan = fetchcore.take_stdin(heap, io, plan);")
    w("    var refused = false;\n    borrow plan as &r in {\n        refused = fetchcore.refused(r);\n    }")
    w("    var status = 0;\n    if refused {\n        borrow plan as &p in {\n            status = fetchcore.refuse(heap, io, p);\n        }\n        fetchcore.drop_plan(heap, plan);\n        return status;\n    }")
    w("    var answer = fetchcore.nothing(heap);\n    var finished = false;\n    while !finished {\n        borrow plan as &p in {\n            let pick = fetchcore.host_of(p);")
    for i in range(n):
        if i == n - 1 and n > 1:
            w("            } else {")
        elif i == 0:
            w("            if pick == 0 {")
        else:
            w("            } else if pick == %d {" % i)
        w("                answer = fetchcore.replace(heap, answer, via_%d(heap, clock, o%d, p, entropy%s));" % (i, i, ", f%d" % i if i in credentials else ""))
    w("            }\n        }")
    w("        var again = false;\n        borrow answer as &a in {\n            again = fetchcore.follows(a);\n        }")
    w("        if again {\n            plan = fetchcore.retarget(heap, plan, answer, hosts());\n            answer = fetchcore.nothing(heap);\n        } else {\n            finished = true;\n        }\n    }")
    w("    borrow plan as &p in {\n        status = fetchcore.respond(heap, io, p, answer);\n    }\n    fetchcore.drop_plan(heap, plan);\n    return status;\n}\n")
    names = ", ".join("o%d" % i for i in range(n))
    narrow = "narrow(out, %s)" % ", ".join('"%s"' % b for b in bounds)
    w("fn main(world: World) -> [] int {")
    w("    let Split { io, ffi, fs, heap, args, out, ports, clock, signals, exec, tty } = split(world);")
    for r in ("ffi", "ports", "signals", "exec", "tty") + (() if https else ("fs",)):
        w("    release(%s);" % r)
    if https:
        cpaths = [credentials[i][0] for i in sorted(credentials)]
        if cpaths:
            w('    let (urandom, %s) = narrow(fs, "/dev/urandom", %s);' % (", ".join("f%d" % i for i in sorted(credentials)), ", ".join('"%s"' % c for c in cpaths)))
        else:
            w('    let urandom = narrow(fs, "/dev/urandom");')
    w("    let %s = %s;" % ("(%s)" % names if n > 1 else names, narrow))
    w("    var status = 0;\n    borrow mut heap as &!h in {\n        borrow args as &g in {\n            borrow mut io as &!i in {\n                borrow clock as &k in {")
    w("                    region seed {\n                        let entropy = alloc_slice[seed](32, byte_of(0));")
    if https:
        w('                        borrow urandom as &uf in {\n                            fs_read(uf, "/dev/urandom", entropy);\n                        }')
    ind = "                        "
    for i in range(n):
        w("%sborrow o%d as &r%d in {" % (ind, i, i))
        ind += "    "
    for i in sorted(credentials):
        w("%sborrow f%d as &s%d in {" % (ind, i, i))
        ind += "    "
    w("%sstatus = run(h, g, i, k, entropy, %s);" % (ind, ", ".join(["r%d" % i for i in range(n)] + ["s%d" % i for i in sorted(credentials)])))
    for i in range(n + len(credentials)):
        ind = ind[:-4]
        w("%s}" % ind)
    w("                    }\n                }\n            }\n        }\n    }")
    if https:
        w("    release(urandom);")
        for i in sorted(credentials):
            w("    release(f%d);" % i)
    for i in range(n):
        w("    release(o%d);" % i)
    w("    release(clock);\n    release(heap);\n    release(args);\n    release(io);\n    return status;\n}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", action="append", required=True)
    ap.add_argument("--allow-private", action="store_true")
    ap.add_argument("--credential", action="append", default=[], help="HOST=PATH[,Header]: the file holding the token sent to that https host (never to another), as Authorization: Bearer, or as the raw value of Header")
    ap.add_argument("--roots", help="PEM bundle embedded as the trust store of every https host")
    ap.add_argument("--out", default="build/fetch")
    ap.add_argument("--no-manifest", action="store_true")
    ap.add_argument("--generate-only", action="store_true", help="write generated/ and the manifest, but do not compile (the committed files are made this way)")
    a = ap.parse_args()
    (ROOT / "generated" / "fetch").mkdir(parents=True, exist_ok=True)
    (ROOT / "generated" / "fetch" / "fetch.cho").write_text(source(a.host, a.allow_private, pathlib.Path(a.roots).read_text() if a.roots else "", parse_credentials(a.host, a.credential)))
    cancho = os.environ.get("CANCHO", "cancho")
    steps = [[cancho, "install"], [sys.executable, str(ROOT / "scripts" / "manifest.py")]]
    if not a.generate_only:
        steps.append([cancho, "build"])
    for cmd in steps:
        if a.no_manifest and "manifest.py" in cmd[-1]:
            continue
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        sys.stdout.write(r.stdout)
        if r.returncode != 0:
            sys.exit(r.stderr + r.stdout)
    return 0


if __name__ == "__main__":
    sys.exit(main())
