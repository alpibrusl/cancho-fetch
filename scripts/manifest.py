#!/usr/bin/env python3
"""The authority manifest: derived by the compiler, embedded by the build,
gated against a ceiling (cancho docs/agent-toolbox.md D12). Adapted from
cancho-table's scripts/manifest.py. Unlike there, `net_out` is allowed -- and
only for the hosts the build was given (`baked_hosts`).

For every [[bin]] in cancho.toml:

1. pass 1: `cancho authority <sources> <installed dependency sources> --std
   --output json`. The dependencies are the files `cancho install` wrote to
   build/deps (one per package module); the authority of a program is the union
   of what its main reaches *through* them, so leaving them out would be
   leaving out most of the program;
2. write manifests/<tool>.authority.json (the committed record) and
   generated/<tool>/built.cho, which holds the authority, the tool's schema
   (schemas/<tool>.v1.json) and the compiler pin as string literals;
3. pass 2: derive again with the new generated file and require the same
   report -- the fixed point;
4. require every derived label to be within the tool's ceiling in tools.toml,
   `bounded` to be true and no foreign symbol.

    python3 scripts/manifest.py            # regenerate, then check
    python3 scripts/manifest.py --check    # change nothing; exit 1 on drift
    python3 scripts/manifest.py --ceiling FILE
        read the ceilings from FILE and not from tools.toml (a gate's mutant: a ceiling without a label the source needs must be refused)
    python3 scripts/manifest.py --against DIR
        also derive the authority with DIR (a cancho-tools `contract/`
        directory at the pinned revision) in place of the installed package,
        and require the same report: the package and the sources it was
        published from say the same thing about what the program may do.

`--check` also compares what the built binary prints (`build/<tool>
introspect`) with the fresh derivation when the binary exists.

The compiler is $CANCHO, or `cancho` on PATH. Run `cancho build` (or
`cancho install`) first: it writes build/deps.
"""

import json
import os
import pathlib
import procs as subprocess  # every child in a group that is reaped: tests/conformance/procs.py
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FORBIDDEN = {"ffi", "net_in"}


def compiler():
    return os.environ.get("CANCHO", "cancho")


def project():
    with open(ROOT / "cancho.toml", "rb") as f:
        return tomllib.load(f)


def sources(entry):
    files = []
    for s in entry["sources"]:
        p = ROOT / s
        if p.is_dir():
            files.extend(sorted(str(x) for x in p.glob("*.cho")))
        else:
            files.append(str(p))
    return files


def installed():
    deps = ROOT / "build" / "deps"
    files = sorted(str(x) for x in deps.glob("*.cho")) if deps.is_dir() else []
    if not files:
        sys.exit("manifest: build/deps is empty; run `cancho install` (or `cancho build`) first")
    return files


def derive(files):
    out = subprocess.run([compiler(), "authority", *files, "--std", "--output", "json"],
                         capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit("cancho authority failed:\n" + out.stdout + out.stderr)
    return json.loads(out.stdout)


def compact(value):
    return json.dumps(value, separators=(",", ":"), ensure_ascii=True)


def literal(text):
    """A cancho string literal: six escapes, no others, one line."""
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 32:
            sys.exit("a control character cannot be written in a cancho literal")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def generated(authority, schema, pin):
    return """edition 5;

module toolbox.built;

// Generated by scripts/manifest.py -- do not edit. The compiler's authority
// report for this tool, the tool's JSON Schema, and the compiler it was
// written for, as `introspect` prints them (cancho docs/agent-toolbox.md D12).
// This module is not in cancho-tools' contract package: each tool has its own.

pub fn authority() -> [] &static [byte] {
    return %s;
}

pub fn schema() -> [] &static [byte] {
    return %s;
}

pub fn compiler() -> [] &static [byte] {
    return %s;
}
""" % (literal(compact(authority)), literal(compact(schema)), literal(pin))


def baked_hosts():
    """The `scheme://host[:port]` entries of generated/fetch/fetch.cho's hosts(), as `host:port` (the port defaults to 80)."""
    text = (ROOT / "generated" / "fetch" / "fetch.cho").read_text()
    start = text.index("fn hosts()")
    literal_ = text[text.index('return "', start) + 8:text.index('";', start)]
    out = set()
    for entry in literal_.split(";"):
        authority = entry.split("://", 1)[-1]
        out.add(authority if ":" in authority else authority + ":80")
    return out


def label_text(label):
    if label["argument"] is None:
        return label["name"]
    return '%s("%s")' % (label["name"], label["argument"])


def gate(tool, authority, ceilings):
    problems = []
    ceiling = ceilings.get(tool)
    if ceiling is None:
        return ["%s: no ceiling in tools.toml" % tool]
    allowed = set(ceiling.get("allow", []))
    if not authority.get("bounded", False):
        problems.append("%s: bounded is false" % tool)
    if authority.get("foreign_symbols"):
        problems.append("%s: foreign symbols %s" % (tool, authority["foreign_symbols"]))
    derived = {l["argument"] for l in authority["labels"] if l["name"] == "net_out"}
    if ceiling.get("net_out") == "baked" and derived != baked_hosts():
        problems.append("%s: net_out is %s but the baked hosts are %s" % (tool, sorted(derived), sorted(baked_hosts())))
    for label in authority["labels"]:
        text = label_text(label)
        if label["name"] == "net_out" and ceiling.get("net_out") == "baked":
            continue
        if label["name"] in FORBIDDEN or label["name"] in ceiling.get("forbid", []):
            problems.append("%s: %s is forbidden to every tool" % (tool, text))
        if text not in allowed:
            problems.append("%s: %s is not within the ceiling in tools.toml" % (tool, text))
    return problems


def introspected(tool):
    binary = ROOT / "build" / tool
    if not binary.exists():
        return None
    out = subprocess.run([str(binary), "introspect"], capture_output=True, text=True)
    if out.returncode != 0:
        return "introspect exited %d" % out.returncode
    return json.loads(out.stdout)["authority"]


def main():
    argv = sys.argv[1:]
    check = "--check" in argv
    against = None
    if "--against" in argv:
        against = pathlib.Path(argv[argv.index("--against") + 1])
    proj = project()
    pin = proj["package"]["cancho"]
    ceiling_file = pathlib.Path(argv[argv.index("--ceiling") + 1]) if "--ceiling" in argv else ROOT / "tools.toml"
    with open(ceiling_file, "rb") as f:
        ceilings = tomllib.load(f)
    bins = proj.get("bin", [])
    problems = []
    if len(bins) > ceilings.get("max_tools", 10):
        problems.append("%d tools; tools.toml allows %d (D1)" % (len(bins), ceilings["max_tools"]))
    deps = installed()
    for entry in bins:
        tool = entry["name"]
        files = sources(entry) + deps
        first = derive(files)
        schema = json.loads((ROOT / "schemas" / ("%s.v1.json" % tool)).read_text())
        record = ROOT / "manifests" / ("%s.authority.json" % tool)
        built = ROOT / "generated" / tool / "built.cho"
        record_text = json.dumps(first, indent=2) + "\n"
        built_text = generated(first, schema, pin)
        if check:
            if not record.exists() or record.read_text() != record_text:
                problems.append("%s: %s is not the compiler's report" % (tool, record.relative_to(ROOT)))
            if not built.exists() or built.read_text() != built_text:
                problems.append("%s: %s is stale" % (tool, built.relative_to(ROOT)))
            embedded = introspected(tool)
            if embedded is not None and embedded != first:
                problems.append("%s: build/%s introspect prints an authority that is not the compiler's (a stale build?)" % (tool, tool))
        else:
            record.parent.mkdir(exist_ok=True)
            record.write_text(record_text)
            built.parent.mkdir(parents=True, exist_ok=True)
            built.write_text(built_text)
            second = derive(files)
            if second != first:
                problems.append("%s: no fixed point -- embedding the manifest changed the authority" % tool)
        if against is not None:
            tree = derive(sources(entry) + sorted(str(x) for x in against.glob("*.cho")))
            if tree != first:
                problems.append("%s: the authority from %s differs from the installed package's" % (tool, against))
            else:
                print("%-8s package == %s (%d functions)" % (tool, against, first["functions"]))
        problems.extend(gate(tool, first, ceilings))
        labels = ", ".join(label_text(l) for l in first["labels"])
        print("%-8s %s" % (tool, labels))
    for p in problems:
        print("FAIL " + p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
